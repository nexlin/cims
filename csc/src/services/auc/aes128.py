_RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]


def _xtime(b: int) -> int:
    b <<= 1
    return (b ^ 0x1b) & 0xff if b & 0x100 else b


def _expand_key(key: bytes) -> list:
    """AES-128 키 스케줄 → 11 라운드 키(각 16바이트 list)."""
    w = [list(key[i:i + 4]) for i in range(0, 16, 4)]
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = t[1:] + t[:1]
            t = [_SBOX[b] for b in t]
            t[0] ^= _RCON[i // 4 - 1]
        w.append([w[i - 4][j] ^ t[j] for j in range(4)])
    return [sum(w[r * 4:r * 4 + 4], []) for r in range(11)]


def _mix_column(c: list) -> list:
    a0, a1, a2, a3 = c
    return [
        _xtime(a0) ^ (_xtime(a1) ^ a1) ^ a2 ^ a3,
        a0 ^ _xtime(a1) ^ (_xtime(a2) ^ a2) ^ a3,
        a0 ^ a1 ^ _xtime(a2) ^ (_xtime(a3) ^ a3),
        (_xtime(a0) ^ a0) ^ a1 ^ a2 ^ _xtime(a3),
    ]


class AES128:
    """단일 블록 암호화 객체 — 키 스케줄을 1회 계산해 재사용한다."""

    def __init__(self, key: bytes) -> None:
        if len(key) != 16:
            raise ValueError("AES-128 key must be 16 bytes")
        self._rk = _expand_key(key)

    def encrypt_block(self, block: bytes) -> bytes:
        if len(block) != 16:
            raise ValueError("block must be 16 bytes")
        s = [b ^ k for b, k in zip(block, self._rk[0])]
        for rnd in range(1, 11):
            s = [_SBOX[b] for b in s]
            # ShiftRows (state is column-major: s[c*4 + r])
            s = [s[((c + r) % 4) * 4 + r] for c in range(4) for r in range(4)]
            if rnd != 10:
                s = sum((_mix_column(s[c * 4:c * 4 + 4]) for c in range(4)), [])
            s = [b ^ k for b, k in zip(s, self._rk[rnd])]
        return bytes(s)


def aes128_encrypt(key: bytes, block: bytes) -> bytes:
    return AES128(key).encrypt_block(block)
