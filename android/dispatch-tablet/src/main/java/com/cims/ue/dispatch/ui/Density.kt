// 태블릿 밀도 — 글자 크기의 **단일 손잡이** (android_dispatch_tablet.md §12).
//
// 이 앱은 데스크톱(1920×1080·마우스)의 화면 의미론을 태블릿(1280×800·터치)으로 옮긴 것이라, 옮기는 동안
// 데스크톱 밀도가 그대로 따라왔다 — 한때 `fontSize` 가 281곳에 9~26sp 열세 가지로 흩어져 있었다. 팔 길이에서
// 읽는 관제석 화면에서 그 아래쪽 값들은 작다. 그래서 **단계는 일곱 개로 줄이고, 값은 한 곳에 둔다.**
//
// 기기에서 보고 한 번에 키우거나 줄이려면 [SCALE] 하나만 바꾼다 — 0.92 면 정비 전 밀도에 가깝다.
//
// 값은 시안 «관제 메뉴 재구성»(android_dispatch_tablet.md §6.3c)의 글자 크기다 — 11 배지 · 12 메타 · 13 본문 · 14 버튼 ·
// 15 카드·구역 제목 · 17 패널 제목 · 20 화면 이름. 26 은 시안에 없는 다이얼 입력용이다.
package com.cims.ue.dispatch.ui

import androidx.compose.ui.unit.sp

/** 글자 크기 단계. 화면 코드는 숫자를 직접 쓰지 않고 이 이름만 쓴다. */
object Type {
    /** 전체 배율 — 1.0 = 설계값. 기기에서 판정한 뒤 이 값만 조정한다. */
    private const val SCALE = 1.0f

    /** 배지·보조 메타의 **최소**. 이보다 작게 두지 않는다. */
    val micro = (11 * SCALE).sp

    /** 칩·표 셀·타임스탬프. */
    val meta = (12 * SCALE).sp

    /** 본문·목록 행. 대부분의 글자가 여기다. */
    val body = (13 * SCALE).sp

    /** 카드 제목·표 머리·강조된 한 줄. */
    val strong = (14 * SCALE).sp

    /** 카드·구역 제목, 목록에서 이름처럼 먼저 읽히는 것(시안 15). */
    val title = (15 * SCALE).sp

    /** 사이드 패널·대화 머리의 제목(시안 17). */
    val head = (17 * SCALE).sp

    /** 상단 바의 이름·배너처럼 한 화면에 하나뿐인 것(시안 20). */
    val display = (20 * SCALE).sp

    /** 다이얼패드 입력처럼 숫자 자체가 화면인 것. */
    val huge = (26 * SCALE).sp
}
